# Stage 1 of the count model: the two measurements the design asks for.
#
#   1. What the general-shape Polya-Gamma sampler costs by shape, and where
#      its time goes on a realistic matrix of counts, to decide whether a
#      saddlepoint sampler is needed for shapes between 13 and 170.
#   2. How well the size is recovered, by how rare the species is.
#
# Design: dev/superpowers/specs/2026-11-12-count-model-design.md (question 9
# and stage 1 of the staged plan). The findings are written up by hand in
# dev/count-model/stage1-report.md.
#
# Run from the package root, once, in the foreground, in one process:
#   Rscript dev/count-model/stage1-checks.R
# Do not edit this file while it is running.

devtools::load_all(quiet = TRUE)
set.seed(20261125)
setOccJSDMSeed(20261125L)

rule <- function(title) cat("\n==== ", title, " ====\n", sep = "")

# ---------------------------------------------------------------------------
rule("Power state and R")
system("pmset -g batt | head -n 1")
system("pmset -g | grep lowpowermode")
cat(R.version.string, "\n")

# ---------------------------------------------------------------------------
rule("Time per draw by shape: seconds for 200,000 draws")
n_draws <- 200000L
shapes <- c(0.5, 1.5, 5.5, 13.5, 50.5, 120.5, 169.5, 171)
predictors <- c(0, -3)
by_shape <- expand.grid(shape = shapes, predictor = predictors)
by_shape$seconds <- NA_real_
for (i in seq_len(nrow(by_shape))) {
  shape <- matrix(by_shape$shape[i], n_draws, 1)
  phi <- matrix(by_shape$predictor[i], n_draws, 1)
  by_shape$seconds[i] <- system.time(samplePGcount_cpp(shape, phi))[["elapsed"]]
}
by_shape$microseconds_per_draw <- 1e6 * by_shape$seconds / n_draws
print(by_shape, row.names = FALSE, digits = 4)

# ---------------------------------------------------------------------------
rule("Where the time goes on a realistic matrix: 250 sites by 300 species")
n_sites <- 250L
n_species <- 300L
centre <- stats::rnorm(n_species, -1, 2)
eta <- sapply(centre, function(m) stats::rnorm(n_sites, m, 1.5))
size <- exp(stats::rnorm(n_species, 0, 1))
# One sample per site at unit effort.
log_mean <- count_log_mean(eta, seq_len(n_sites), rep(0, n_sites))
y <- sapply(seq_len(n_species), function(s) {
  stats::rnbinom(n_sites, size = size[s], mu = exp(log_mean[, s]))
})
size_mat <- matrix(size, n_sites, n_species, byrow = TRUE)
shape <- y + size_mat
phi <- log_mean - log(size_mat)

cat("Share of counts that are zero: ", round(mean(y == 0), 4), "\n", sep = "")
cat("Largest count: ", max(y), "\n", sep = "")
cat("Quantiles of the shape (count plus size):\n")
print(round(stats::quantile(shape, c(0.5, 0.9, 0.99, 0.999, 1)), 2))
cat("Quantiles of the predictor (log mean minus log size):\n")
print(round(stats::quantile(phi, c(0, 0.01, 0.5, 0.99, 1)), 2))

# The route samplePGcount_cpp() takes for each cell, in the order it tests.
extreme <- abs(phi) > 12
route <- ifelse(extreme, "extreme predictor",
          ifelse(shape > 170, "shape above 170",
          ifelse(shape > 13, "shape from 13 to 170", "shape up to 13")))
routes <- c("extreme predictor", "shape up to 13", "shape from 13 to 170",
            "shape above 170")
repeats <- 20L
time_route <- function(cells) {
  if (!any(cells)) return(0)
  s <- matrix(shape[cells], ncol = 1)
  p <- matrix(phi[cells], ncol = 1)
  system.time(for (k in seq_len(repeats)) samplePGcount_cpp(s, p))[["elapsed"]]
}
by_route <- data.frame(route = routes)
by_route$cells <- vapply(routes, function(r) sum(route == r), numeric(1))
by_route$share_of_cells <- by_route$cells / length(shape)
by_route$seconds_20_repeats <- vapply(routes, function(r) time_route(route == r), numeric(1))
by_route$share_of_time <- by_route$seconds_20_repeats / sum(by_route$seconds_20_repeats)
print(by_route, row.names = FALSE, digits = 4)
whole <- system.time(for (k in seq_len(repeats)) samplePGcount_cpp(shape, phi))[["elapsed"]]
cat("Seconds for one draw of the whole matrix (mean of ", repeats, "): ",
    signif(whole / repeats, 4), "\n", sep = "")

# ---------------------------------------------------------------------------
rule("Size recovery by rarity: 60 species by 250 sites, known log mean")
n_sites <- 250L
n_species <- 60L
truth <- rep(c(0.5, 5), length.out = n_species)
centre <- seq(-4, 3, length.out = n_species)
eta <- sapply(centre, function(m) stats::rnorm(n_sites, m, 1))
log_mean <- count_log_mean(eta, seq_len(n_sites), rep(0, n_sites))
y <- sapply(seq_len(n_species), function(s) {
  stats::rnbinom(n_sites, size = truth[s], mu = exp(log_mean[, s]))
})
include <- matrix(TRUE, n_sites, n_species)

iterations <- 5000L
burn <- 2000L
prior_sd <- 1
r <- rep(1, n_species)
step <- rep(count_size_initial_step, n_species)
t <- 0L
draws <- matrix(NA_real_, iterations - burn, n_species)
accepted <- matrix(NA, iterations - burn, n_species)
for (it in seq_len(iterations)) {
  o <- count_size_step(r, y, log_mean, include, prior_sd, step, it <= burn, t)
  r <- o$r
  step <- o$step
  t <- o$t
  if (it > burn) {
    draws[it - burn, ] <- r
    accepted[it - burn, ] <- o$accepted
  }
}

q <- apply(draws, 2, stats::quantile, c(0.025, 0.5, 0.975))
nonzero <- colSums(y > 0)
per_species <- data.frame(
  species = seq_len(n_species),
  centre = round(centre, 2),
  truth = truth,
  nonzero = nonzero,
  lower = signif(q[1, ], 3),
  median = signif(q[2, ], 3),
  upper = signif(q[3, ], 3),
  covers = truth >= q[1, ] & truth <= q[3, ],
  acceptance = round(colMeans(accepted), 2)
)
print(per_species, row.names = FALSE)

group <- cut(nonzero, c(-Inf, 9, 49, 149, Inf),
             labels = c("under 10", "10 to 49", "50 to 149", "150 and over"))
summarise_group <- function(rows) {
  data.frame(
    species = sum(rows),
    median_log_error = stats::median(log(q[2, rows] / truth[rows])),
    coverage_95 = mean(per_species$covers[rows]),
    median_upper_over_lower = stats::median(q[3, rows] / q[1, rows])
  )
}
by_group <- do.call(rbind, lapply(levels(group), function(g) {
  rows <- group == g
  if (!any(rows)) return(data.frame(species = 0, median_log_error = NA,
                                    coverage_95 = NA, median_upper_over_lower = NA))
  summarise_group(rows)
}))
by_group <- cbind(nonzero_counts = levels(group), by_group)
cat("\nBy number of non-zero counts, all species:\n")
print(by_group, row.names = FALSE, digits = 3)

for (size_value in c(0.5, 5)) {
  cat("\nBy number of non-zero counts, true size ", size_value, ":\n", sep = "")
  sub <- do.call(rbind, lapply(levels(group), function(g) {
    rows <- group == g & truth == size_value
    if (!any(rows)) return(data.frame(species = 0, median_log_error = NA,
                                      coverage_95 = NA, median_upper_over_lower = NA))
    summarise_group(rows)
  }))
  print(cbind(nonzero_counts = levels(group), sub), row.names = FALSE, digits = 3)
}

rule("Done")
