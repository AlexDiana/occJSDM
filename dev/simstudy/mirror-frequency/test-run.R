# Standalone tests for run.R, launch.R and analyse.R of the mirror-frequency
# check. Run with `Rscript test-run.R` from this directory. Tests that need
# the pr11 archive, the community-5 input or the study library are skipped
# when they are absent; they read those files and write only to temporary
# directories.
library(testthat)
source('run.R')
source('launch.R')
source('analyse.R')

archives <- Sys.getenv('OCCJSDM_ARCHIVES','/Users/douglasyu/src/occJSDM/dev/simstudy/results')
study <- file.path(archives,'mirror-frequency-20261013')
inputs_root <- file.path(archives,'intercept-prior-inputs')
have_archives <- dir.exists(file.path(archives,PR11_ARCHIVE)) && dir.exists(inputs_root)
have_library <- have_archives && dir.exists(file.path(study,'library/occJSDM')) && file.exists(file.path(SCRIPT_REPO,FINGERPRINT_FILE))
need_archives <- function() if(!have_archives) skip('pr11 archive or community-5 inputs not available')
need_library <- function() if(!have_library) skip('study library not available')

test_that('stages, repeats and seeds are the frozen ones, distinct across stages and from the diagnosis seeds', {
  expect_identical(STAGES,c('a','b','pilot'))
  expect_identical(REPEATS,list(a=1:25,b=1:25,pilot=1L))
  seeds <- c(repeat_seed('a',REPEATS$a),repeat_seed('b',REPEATS$b),repeat_seed('pilot',REPEATS$pilot))
  expect_identical(anyDuplicated(seeds),0L)
  expect_false(any(seeds %in% (20261001L+1:16)))
  expect_identical(repeat_seed('a',1L),20261101L)
  expect_identical(repeat_seed('b',25L),20261225L)
  expect_identical(repeat_seed('pilot',1L),20261051L)
  expect_identical(unname(PR11_LONG),c(4,6000,12000,1))
  expect_identical(STAGE_B_NBURN,24000)
})

test_that('stage schedules come from the pr11 archive', {
  need_archives()
  a <- stage_mcmc('a',archives)
  expect_identical(names(a),c('nchain','nburn','niter','nthin'))
  expect_equal(unname(unlist(a)),unname(PR11_LONG))
  b <- stage_mcmc('b',archives)
  expect_equal(b$nburn,24000)
  expect_identical(typeof(b$nburn),typeof(a$nburn))
  expect_identical(b[c('nchain','niter','nthin')],a[c('nchain','niter','nthin')])
  expect_identical(stage_mcmc('pilot',archives),PILOT_MCMC)
  expect_error(run_spec('a',26L,archives),'must be one of')
  expect_error(run_spec('c',1L,archives),'--stage must be')
  s <- run_spec('b',7L,archives)
  expect_identical(s$seed,20261207L)
  expect_identical(iterations_run(s$mcmc),4*(24000+12000))
  expect_identical(iterations_run(run_spec('a',1L,archives)$mcmc),4*(6000+12000))
})

test_that('argument parsing, repeat lists and file names', {
  need_archives()
  o <- parse_run_args(c('--repo=x','--study=y','--inputs-root=z','--stage=a','--repeat=3',paste0('--archives=',archives)))
  expect_identical(o$spec$repeat_index,3L)
  expect_identical(basename(fit_file('/s',o$spec)),'repeat-03-fit.rds')
  expect_identical(basename(dirname(fit_file('/s',o$spec))),'stage-a')
  expect_error(parse_run_args(c('--repo=x','--study=y','--inputs-root=z','--stage=a','--repeat=x',paste0('--archives=',archives))),'whole number')
  q <- parse_repeats('2-4','a',archives)
  expect_identical(q$repeat_index,2:4)
  expect_identical(q$label[1],'stage-a-repeat-02')
  expect_identical(q$seed,20261100L+2:4)
  expect_error(parse_repeats('4-2','a',archives),'backwards')
  expect_error(parse_repeats('1-26','a',archives),'must be one of')
  expect_identical(parse_repeats('1','pilot',archives)$repeat_index,1L)
})

test_that('the fitting statement is the pr11 one with its fitter replaced', {
  need_archives()
  runner <- pr11_runner(SCRIPT_REPO,archives)
  expr <- with_intercept_prior(runner$expr)
  text <- deparse(expr)
  expect_true(any(grepl('.fitter',text,fixed=TRUE)))
  expect_false(any(grepl('runOccJSDM',text,fixed=TRUE)))
  src <- pr11_job(archives,inputs_root)
  expect_identical(src$job$priors,list(a_q=1,b_q=20))
  expect_true(file.exists(src$input_file))
  expect_identical(unname(tools::md5sum(src$input_file)),src$input_md5)
})

test_that('a tiny four-chain fit is reproducible from its seed, passes the post-fit checks and analyses', {
  need_library()
  pkg <- load_study_library(study)
  runner <- pr11_runner(SCRIPT_REPO,archives);expr <- with_intercept_prior(runner$expr)
  src <- pr11_job(archives,inputs_root);prepared <- prepare_input(src)
  tiny <- list(nchain=4,nburn=3,niter=5,nthin=1)
  spec <- list(stage='pilot',repeat_index=1L,seed=repeat_seed('pilot',1L),mcmc=tiny)
  recorder <- new.env()
  result <- evaluate_seeded(expr,prepared$input,prepared$job,tiny,bindings=list(.fitter=make_fitter(recorder)),seed=spec$seed)
  saved <- c(list(job=prepared$job,input_file=prepared$input_file,key=KEY,stage='pilot',repeat_index=1L,seed=spec$seed,mcmc=tiny,
      source_revision=readLines(file.path(study,'source-revision.txt'))),result,
    list(listPriors_used=recorder$listPriors,elapsed_seconds=as.numeric(difftime(result$finished,result$started,units='secs')),
      input_md5_after=unname(tools::md5sum(prepared$input_file)),loaded_library=pkg))
  expect_silent(check_saved_fit(saved,spec,prepared,src$job$priors,pkg))
  expect_identical(dim(saved$fit$results_output$theta0_output),c(10L,5L,4L))
  expect_identical(saved$listPriors_used,list(a_q=1,b_q=20))
  again <- evaluate_seeded(expr,prepared$input,prepared$job,tiny,bindings=list(.fitter=make_fitter(new.env())),seed=spec$seed)
  expect_identical(again$fit$results_output$theta0_output,saved$fit$results_output$theta0_output)
  expect_identical(again$rng_final,saved$rng_final)
  other <- evaluate_seeded(expr,prepared$input,prepared$job,tiny,bindings=list(.fitter=make_fitter(new.env())),seed=spec$seed+1L)
  expect_false(identical(other$fit$results_output$theta0_output,saved$fit$results_output$theta0_output))
  tmp <- tempfile('mirror-study-');dir.create(file.path(tmp,'fits','stage-pilot'),recursive=TRUE)
  saveRDS(saved,file.path(tmp,'fits','stage-pilot','repeat-01-fit.rds'))
  out <- tempfile('mirror-results-')
  res <- analyse_stage(SCRIPT_REPO,tmp,inputs_root,archives,'pilot',repeats=1L,out=out)
  expect_identical(nrow(res$regions),4L)
  expect_identical(res$regions$position,1:4)
  expect_identical(res$regions$repeat_index,rep(1L,4))
  expect_true(all(res$regions$region %in% REGIONS))
  expect_identical(res$summary$n_chains,4L)
  expect_identical(res$summary$n_near_truth+res$summary$n_mirror+res$summary$n_both+res$summary$n_unknown,4L)
  expect_identical(nrow(res$per_repeat),1L)
  expect_match(readLines(file.path(out,'decision.txt')),'^run_stage_b: (yes|no)$')
  expect_true(all(c('chain-regions.csv','repeat-summary.csv','summary.csv','decision.txt') %in% list.files(out)))
  expect_error(analyse_stage(SCRIPT_REPO,tmp,inputs_root,archives,'pilot',repeats=1:2,out=out),'Missing fit file')
})
