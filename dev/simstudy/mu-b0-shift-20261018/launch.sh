#!/bin/sh
# One step of the run, named by the first argument; see README.md.
#   drift: the three fits of the mu_b0 drift diagnostic (base_rare_cm_s100
#          replicates 3 and 4, base_cm_s100 replicate 2) refitted with the
#          shift step on, at 5,000 + 500 x 10 (5,000 + 5,000 with every 10th
#          draw stored) and the latent states kept (refit-drift.R); 3 workers.
#   main:  the 100-species mixing check rerun with the shift step on:
#          replicates 1 to $2 of base_cm_s100 and base_rare_cm_s100 at
#          5,000 + 5,000, keeping draws (refit-s100.R); 5 workers.
# One RcppParallel thread and one BLAS thread per fit. The steps run one
# after the other, so the laptop never has more than 5 fitting workers.
# Launched detached from a non-interactive shell:
#   nohup perl -MPOSIX -e 'POSIX::setsid() or die; exec @ARGV or die' sh -c 'sh launch.sh drift; sh launch.sh main 5' > launch-main.log 2>&1 < /dev/null &
# Logs, provenance and draws go to paths that .gitignore lists, so each step
# records a clean tree. Do not edit this file while a step is running: sh
# reads it lazily.
set -u
STEP=$1
WT=/Users/douglasyu/src/occJSDM/.claude/worktrees/nervous-kirch-56dc48
RUN=$WT/dev/simstudy/mu-b0-shift-20261018
RSCRIPT=/usr/local/bin/Rscript
JOBS=base_rare_cm_s100:3,base_rare_cm_s100:4,base_cm_s100:2
ARMS=base_cm_s100,base_rare_cm_s100
export VECLIB_MAXIMUM_THREADS=1
export RCPP_PARALLEL_NUM_THREADS=1
cd "$RUN"
case "$STEP" in
  drift) OUT=$RUN/draws/drift; CORES=3; NB=5000; NI=500; NT=10
         SETTINGS="$JOBS, nburn = $NB, niter = $NI, nthin = $NT, nchain = 2, cores = $CORES, threads = 1, b0_shift at its defaults" ;;
  main)  OUT=$RUN/draws/main; CORES=5; REPS=1-${2:?main needs the replicate count}; NB=5000; NI=5000
         SETTINGS="replicates $REPS of $ARMS, nburn = $NB, niter = $NI, nchain = 2, cores = $CORES, threads = 1, b0_shift at its defaults" ;;
  *) echo "unknown step: $STEP" >&2; exit 2 ;;
esac
if [ -e "$OUT" ]; then echo "refusing: $OUT exists" >&2; exit 1; fi
{
  echo "step: $STEP"
  echo "launched: $(date '+%F %T')"
  echo "revision: $(git -C "$WT" rev-parse HEAD)"
  echo "branch: $(git -C "$WT" rev-parse --abbrev-ref HEAD)"
  echo "dirty files: $(git -C "$WT" status --porcelain | wc -l | tr -d ' ')"
  echo "R: $("$RSCRIPT" -e 'cat(R.version.string)')"
  echo "BLAS: $("$RSCRIPT" -e 'cat(extSoftVersion()[["BLAS"]])')"
  echo "VECLIB_MAXIMUM_THREADS seen by R: $("$RSCRIPT" -e 'cat(Sys.getenv("VECLIB_MAXIMUM_THREADS"))')"
  echo "lowpowermode: $(pmset -g | awk '/lowpowermode/ {print $2}')"
  echo "power: $(pmset -g batt | head -1)"
  echo "other R processes at launch: $(ps -eo pcpu,args | grep -E 'exec/R|Rscript' | grep -v grep | awk '$1 > 5' | wc -l | tr -d ' ') using over 5% CPU"
  echo "settings: $SETTINGS"
} > "$STEP-provenance.txt"
echo $$ > "$STEP-launcher.pid"
if [ "$STEP" = drift ]; then
  "$RSCRIPT" "$RUN/refit-drift.R" "$WT" "$OUT" "$CORES" "$JOBS" "$NB" "$NI" "$NT" > "$STEP.log" 2>&1 &
else
  "$RSCRIPT" "$RUN/refit-s100.R" "$WT" "$OUT" "$CORES" "$ARMS" "$REPS" "$NB" "$NI" > "$STEP.log" 2>&1 &
fi
RPID=$!
echo $RPID > "$STEP-rscript.pid"
caffeinate -i -w $RPID &
wait $RPID
status=$?
echo "exit status: $status at $(date '+%F %T')" >> "$STEP-provenance.txt"
echo "ALL DONE $(date '+%F %T') status $status" >> "$STEP.log"
