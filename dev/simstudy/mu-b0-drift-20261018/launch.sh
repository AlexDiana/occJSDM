#!/bin/sh
# One step of the run, named by the first argument; see README.md.
#   check: check-storage.R, the storage check, in the foreground (a few
#          minutes); writes storage-check.csv.
#   main:  refit.R on base_rare_cm_s100 replicates 3 and 4 and base_cm_s100
#          replicate 2 at 5,000 + 500 x 10 (the main run's 5,000 + 5,000 with
#          every 10th draw stored), keeping the latent terms; 3 workers.
# One RcppParallel thread and one BLAS thread per fit. Launched from a
# non-interactive shell; the main step detached:
#   sh launch.sh check
#   nohup perl -MPOSIX -e 'POSIX::setsid() or die; exec @ARGV or die' sh launch.sh main > launch-main.log 2>&1 < /dev/null &
# Logs, provenance and draws go to paths that .gitignore lists, so each step
# records a clean tree. Do not edit this file while a step is running: sh
# reads it lazily.
set -u
STEP=$1
WT=/Users/douglasyu/src/occJSDM/.claude/worktrees/stoic-volhard-8d403c
RUN=$WT/dev/simstudy/mu-b0-drift-20261018
RSCRIPT=/usr/local/bin/Rscript
JOBS=base_rare_cm_s100:3,base_rare_cm_s100:4,base_cm_s100:2
export VECLIB_MAXIMUM_THREADS=1
export RCPP_PARALLEL_NUM_THREADS=1
cd "$RUN"
case "$STEP" in
  check) OUT=$RUN/storage-check.csv
         SETTINGS="check-storage.R: base_rare_cm_m3 replicate 1 at 50 + 100 and base_rare_cm_s100 replicate 3 at 20 + 40, nthin 1 against 10, one process" ;;
  main)  OUT=$RUN/draws/main; CORES=3; NB=5000; NI=500; NT=10
         SETTINGS="$JOBS, nburn = $NB, niter = $NI, nthin = $NT, nchain = 2, cores = $CORES, threads = 1" ;;
  *) echo "unknown step: $STEP" >&2; exit 2 ;;
esac
if [ -e "$OUT" ]; then echo "refusing: $OUT exists" >&2; exit 1; fi
{
  echo "step: $STEP"
  echo "launched: $(date '+%F %T')"
  echo "revision: $(git -C "$WT" rev-parse HEAD)"
  echo "branch: $(git -C "$WT" rev-parse --abbrev-ref HEAD)"
  echo "dirty files: $(git -C "$WT" status --porcelain | wc -l | tr -d ' ')"
  echo "R: $("$RSCRIPT" -e 'cat(R.version.string)')"
  echo "BLAS: $("$RSCRIPT" -e 'cat(extSoftVersion()[["BLAS"]])')"
  echo "VECLIB_MAXIMUM_THREADS seen by R: $("$RSCRIPT" -e 'cat(Sys.getenv("VECLIB_MAXIMUM_THREADS"))')"
  echo "lowpowermode: $(pmset -g | awk '/lowpowermode/ {print $2}')"
  echo "power: $(pmset -g batt | head -1)"
  echo "settings: $SETTINGS"
} > "$STEP-provenance.txt"
echo $$ > "$STEP-launcher.pid"
if [ "$STEP" = check ]; then
  "$RSCRIPT" "$RUN/check-storage.R" "$WT" "$OUT" > "$STEP.log" 2>&1 &
else
  "$RSCRIPT" "$RUN/refit.R" "$WT" "$OUT" "$CORES" "$JOBS" "$NB" "$NI" "$NT" > "$STEP.log" 2>&1 &
fi
RPID=$!
echo $RPID > "$STEP-rscript.pid"
caffeinate -i -w $RPID &
wait $RPID
status=$?
echo "exit status: $status at $(date '+%F %T')" >> "$STEP-provenance.txt"
echo "ALL DONE $(date '+%F %T') status $status" >> "$STEP.log"
