library(testthat)
source("../archive.R"); source("../runner.R"); source("../repair-runtime.R")
fixture <- function(completed=TRUE) {
  root <- tempfile(); path <- file.path(root,"Hmsc-env-rep01-spread/attempts/01"); dir.create(path,recursive=TRUE)
  request <- list(mode="fit",job=list(package="Hmsc"),identity=c(snapshot="frozen"),settings=list(attempt_id=1L))
  write_once(request,file.path(path,"request.rds"))
  write_once(list(fit=list(package="Hmsc",elapsed_seconds=1)),file.path(path,"fit.rds"))
  write_once(data.frame(failed=FALSE),file.path(path,"diagnostics.rds"))
  write_once(list(p_full=matrix(.5,2,2)),file.path(path,"training-prediction.rds"))
  writeLines(c("Error in verify_package_identity(packages) : ","  Loaded runtime package mismatch: Hmsc","Calls: worker_task -> verify_package_identity","Execution halted"),file.path(path,"stderr.log"))
  jsonlite::write_json(list(exit_status=1L,elapsed_seconds=2),file.path(path,"exit.json"),auto_unbox=TRUE)
  if(completed) complete_attempt(path,request$identity,list(status="interrupted",reason="Worker exit 1"))
  path
}
test_that("recovery preserves administrative records and native artifacts without refitting", {
  p <- fixture(); original <- md5(file.path(p,c("summary.rds","complete.rds","fit.rds")))
  expect_true(recover_hmsc_attempt(p,c(patch="test")))
  expect_equal(md5(file.path(p,"version-recovery",c("original-summary.rds","original-complete.rds"))),original[1:2])
  expect_equal(md5(file.path(p,"fit.rds")),original[3])
  expect_equal(resume_state(p,c(snapshot="frozen"))$status,"complete")
  expect_true(readRDS(file.path(p,"summary.rds"))$acceptable)
  expect_false(recover_hmsc_attempt(p,c(patch="test")))
  write_once(list(status="selected"),file.path(dirname(dirname(p)),"selection.rds"))
  expect_false(recover_hmsc_attempt(p,c(patch="test")))
  expect_error(recover_hmsc_attempt(p,c(patch="changed")),"identity")
})
test_that("interruption between removing old summary and completion resumes safely", {
  p <- fixture(); recover_hmsc_attempt(p,c(patch="test"))
  unlink(file.path(p,"summary.rds"))
  file.copy(file.path(p,"version-recovery/original-complete.rds"),file.path(p,"complete.rds"),overwrite=TRUE)
  expect_true(recover_hmsc_attempt(p,c(patch="test")))
  expect_equal(resume_state(p,c(snapshot="frozen"))$status,"complete")
})
test_that("recovery also finalises uncollected attempts", {
  p <- fixture(FALSE)
  expect_true(recover_hmsc_attempt(p,c(patch="test")))
  expect_length(readRDS(file.path(p,"version-recovery/receipt.rds"))$original_records,0L)
  expect_false(recover_hmsc_attempt(p,c(patch="test")))
  write_once(list(status="selected"),file.path(dirname(dirname(p)),"selection.rds"))
  expect_false(recover_hmsc_attempt(p,c(patch="test")))
})
test_that("unrelated errors, incomplete artifacts and completed selections are rejected", {
  p <- fixture(); writeLines("Different error",file.path(p,"stderr.log"))
  expect_error(recover_hmsc_attempt(p,c(patch="test")),"isolated")
  p <- fixture(FALSE); unlink(file.path(p,"fit.rds"))
  expect_error(recover_hmsc_attempt(p,c(patch="test")),"Incomplete")
  p <- fixture(); write_once(list(status="selected"),file.path(dirname(dirname(p)),"selection.rds"))
  expect_error(recover_hmsc_attempt(p,c(patch="test")),"selection")
})
