library(testthat)
for(f in c("basis.R","adapter-contract.R","score.R","attribution.R")) if(file.exists(file.path("..",f))) source(file.path("..",f))
test_that("known fields distinguish pattern, realised amplitude and flat baselines", {
  t <- c(-1,0,1); p <- .5*t
  s <- field_metrics(p,t,"logit")
  expect_equal(s$rmse,sqrt(1/6)); expect_equal(s$attenuation,.5)
  expect_equal(s$correlation,1); expect_equal(s$realised_sd, .5)
  expect_equal(s$truth_realised_sd,1)
  flat <- field_metrics(rep(0,3),t,"logit")
  expect_true(is.na(flat$correlation)); expect_equal(flat$correlation_status,"constant fitted field")
  expect_equal(flat$rmse_reduction,0)
  expect_error(field_metrics(p,t,"probit",require_matching_link=TRUE),"matching")
})
test_that("predictive attribution is additive, allows negative values and counts clamps", {
  p <- list(site_id=c("a","b"),species_id=c("s1","s2"),
    p_full=matrix(c(.7,.1,.2,1),2),p_space_zero=matrix(.5,2,2),p_env_zero=matrix(.4,2,2),p_both_zero=matrix(.5,2,2))
  z <- matrix(c(1,1,0,0),2)
  a <- attribute_sites(p,z)
  expect_lt(min(a$space),0)
  expect_lt(max(abs(a$environment+a$space-a$total_gain)),1e-10)
  expect_equal(sum(a$clamped),1L)
  expected <- attribute_sites(p,matrix(.3,2,2),expected=TRUE)
  hand <- .3*log(.7)+.7*log(.3)
  expect_equal(expected$LES[1],hand)
  expect_equal(p$p_full[2,2],1)
})
test_that("empty bins and all-zero species remain explicit", {
  got <- probability_metrics(c(.2,.3),c(.1,.5),c(0,0))
