test_that("complete scoring preserves species, empty strata and compatible intervals", {
  ids <- list(site_id=c("a","b","c"),species_id=c("s1","s2"))
  terms <- center_terms(c(-2,1),matrix(c(-.2,0,.2,.2,0,-.2),3,2),matrix(c(-1,0,1,1,0,-1),3,2),c(0,0),c(0,0))
  p <- point_prediction(ids,terms,plogis,"logit","fixture")
  t <- c(ids,list(probabilities=p,field=terms$spatial,states=matrix(c(0,0,0,1,0,1),3,2),
    xy=rbind(c(0,0),c(.5,.5),c(1,1)),training_xy=rbind(c(0,0),c(.5,.5),c(1,1)),training_states=matrix(c(0,0,0,1,0,1),3,2),prevalence=c(.05,.75),generating_sd=1))
  s <- score_predictions(p,t,p)
  expect_equal(s$species$rmse,c(0,0)); expect_equal(s$species$training_occurrences,c(0,2))
  expect_true(any(s$strata$status=="empty")); expect_equal(nrow(s$strata),2*7*3)
  expect_true(all(s$species$interval_status=="unavailable"))
  expect_equal(s$species$space_zero_benefit,s$species$space_zero_rmse)
  expect_lt(max(abs(s$sites$expected$environment+s$sites$expected$space-s$sites$expected$total_gain)),1e-10)
})
test_that("failed cells retain every species and prediction scope", {
  jobs <- data.frame(key=c("env-a","gp-a"),package="occJSDM",arm=c("env","gp"),community="rep01",arrangement="spread",kind="comparison",species=NA_character_)
  accounting <- cbind(jobs,status=c("selected","failed"),training_supported=c(TRUE,FALSE),lattice_supported=c(TRUE,FALSE))
  observed <- data.frame(key="env-a",scope="training",species_id="s1",rmse=.1)
  got <- complete_species_grid(observed,accounting,c(s1=.05,s2=.75))
  expect_equal(nrow(got),8L)
  expect_equal(sum(got$prediction_status=="unavailable"),4L)
  expect_equal(sum(is.finite(got$rmse)),1L)
  expect_equal(sort(unique(got$species_id)),c("s1","s2"))
})
