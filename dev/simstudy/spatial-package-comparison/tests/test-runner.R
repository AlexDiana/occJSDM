library(testthat)
for(f in c("config.R","archive.R","basis.R","adapter-contract.R","diagnostics.R","select.R","runner.R")) if(file.exists(file.path("..",f))) source(file.path("..",f))
attempt <- function(id,objective=1,gradient=0,p=.4,ok=TRUE) list(attempt_id=id,status="complete",objective=objective,acceptable=ok,stationarity=gradient,training_probability=matrix(p,2,2),diagnostics=data.frame(failed=!ok))
test_that("point starts obey the finite three-plus-three rule without truth", {
  a <- lapply(1:3,attempt)
  expect_equal(select_attempts(a,study_config(),"point")$selected_attempt,1L)
  expect_equal(select_attempts(a[1:2],study_config(),"point")$next_attempts,3L)
  a[[2]]$training_probability[,] <- .5; a[[3]]$objective <- 2
  expect_equal(select_attempts(a,study_config(),"point")$next_attempts,4:6)
  b <- c(a,lapply(4:6,function(i)attempt(i,2,p=.5)))
  expect_equal(select_attempts(b,study_config(),"point")$status,"unstable")
  b[[6]] <- attempt(6)
  expect_equal(select_attempts(b,study_config(),"point")$status,"selected")
  expect_equal(select_attempts(lapply(1:3,function(i)attempt(i,ok=FALSE)),study_config(),"point")$status,"failed")
  b[[1]]$status <- "resource_interrupted"
  expect_equal(select_attempts(b,study_config(),"point")$status,"budget_amendment_required")
})
test_that("MCMC diagnostics exempt only declared structural constants", {
  set.seed(21); good <- matrix(rnorm(8000),2000,4)
  expect_false(trace_diagnostic(good,"ok")$failed)
  expect_true(trace_diagnostic(matrix(1,2000,4),"degenerate")$failed)
  expect_false(trace_diagnostic(matrix(0,2000,4),"structural",structural=TRUE)$failed)
  bad <- attempt(1,ok=FALSE)
  expect_equal(select_attempts(list(bad),study_config(),"bayesian")$next_attempts,2L)
  expect_equal(select_attempts(list(bad,attempt(2,ok=FALSE)),study_config(),"bayesian")$status,"unresolved_diagnostics")
})
test_that("completion is atomic, hash-bound and preserves different results", {
  root <- tempfile(); dir.create(root); expected <- c(source="abc",input="def")
  write_once(list(partial=TRUE),file.path(root,"fit.rds"))
  expect_equal(resume_state(root,expected)$status,"interrupted")
  complete_attempt(root,expected,list(status="complete",attempt_id=1L))
  expect_equal(resume_state(root,expected)$status,"complete")
  expect_error(resume_state(root,c(source="changed",input="def")),"identity")
  writeBin(as.raw(3),file.path(root,"fit.rds"))
  expect_error(resume_state(root,expected),"hash")
})
