test_that("runtime projection is conservative and labels extrapolation", {
  d <- data.frame(package=c("occJSDM","occJSDM","sjSDM"),arm=c("gp","gp","dnn"),attempt_id=c(1,2,1),seconds=c(7,24,3))
  p <- data.frame(package=c("occJSDM","sjSDM"),arm=c("gp","dnn"),attempt_id=c(2,1),seconds=c(4,1))
  remain <- data.frame(package=c("occJSDM","sjSDM"),arm=c("gp","dnn"),cells=c(10,10))
  out <- project_runtime(d,p,remain,study_config())
  expect_equal(out$arms$seconds_per_cell,c(35,19))
  expect_gte(out$remaining_hours*3600,540/4)
  expect_match(out$arms$extension_cost[1],"measured")
  estimated <- project_runtime(d[d$attempt_id==1,],p,remain,study_config())
  expect_match(estimated$arms$extension_cost[1],"scaled")
  expect_false(project_runtime(d,p[FALSE,],remain,study_config())$passed)
})
test_that("external archives retain their identity and determine storage checks", {
  root <- tempfile(); dir.create(root); target <- tempfile(); dir.create(target)
  jobs <- file.path(target,"jobs"); dir.create(jobs); file.symlink(jobs,file.path(root,"jobs"))
  sentinel <- file.path(target,"identity"); writeLines("volume:study",sentinel)
  jsonlite::write_json(list(schema_version=1L,jobs_path=normalizePath(jobs),sentinel_path=sentinel,sentinel_value="volume:study"),file.path(root,"storage-record.json"),auto_unbox=TRUE)
  expect_identical(verify_storage(root),normalizePath(jobs))
  writeLines("different",sentinel)
  expect_error(verify_storage(root),"identity")
  unlink(sentinel)
  expect_error(verify_storage(root),"unavailable")
})
test_that("scientific dispatch requires current certification and review", {
