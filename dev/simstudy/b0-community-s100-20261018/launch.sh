#!/bin/sh
# One step of the run, named by the first argument; see README.md.
#   timing: replicates 1 to 5 of both 100-species arms at 200 + 200.
#   s10:    replicates 1 to 5 of the 10-species arms base_cm_m3 and
#           base_rare_cm_m3 at 5,000 + 5,000, keeping draws.
#   main:   replicates 1 to $2 of both 100-species arms at 5,000 + 5,000,
#           keeping draws.
# 5 worker processes, one RcppParallel thread and one BLAS thread per fit in
# every step; the steps run one at a time, so the laptop never has more than 5
# fitting workers. Launched detached from a non-interactive shell. Every
# output goes to a path that .gitignore lists, so each step records a clean
# tree. Do not edit this file while a step is running: sh reads it lazily.
set -u
STEP=$1
WT=/Users/douglasyu/src/occJSDM/.claude/worktrees/nostalgic-mendel-8b7449
RUN=$WT/dev/simstudy/b0-community-s100-20261018
REFIT=$WT/dev/simstudy/theta-community-mean-20261016/refit.R
RSCRIPT=/usr/local/bin/Rscript
S100=base_cm_s100,base_rare_cm_s100
S10=base_cm_m3,base_rare_cm_m3
export VECLIB_MAXIMUM_THREADS=1
export RCPP_PARALLEL_NUM_THREADS=1
cd "$RUN"
case "$STEP" in
  timing) OUT=$RUN/draws/timing; ARMS=$S100; REPS=1-5; NB=200; NI=200 ;;
  s10)    OUT=$RUN/draws/s10; ARMS=$S10; REPS=1-5; NB=5000; NI=5000 ;;
  main)   OUT=$RUN/draws/main; ARMS=$S100; REPS=1-${2:?main needs the replicate count}; NB=5000; NI=5000 ;;
  *) echo "unknown step: $STEP" >&2; exit 2 ;;
esac
if [ -e "$OUT" ]; then echo "refusing: $OUT exists" >&2; exit 1; fi
{
  echo "step: $STEP"
  echo "launched: $(date '+%F %T')"
  echo "revision: $(git -C "$WT" rev-parse HEAD)"
  echo "branch: $(git -C "$WT" rev-parse --abbrev-ref HEAD)"
  echo "dirty files: $(git -C "$WT" status --porcelain | wc -l | tr -d ' ')"
  echo "R: $("$RSCRIPT" -e 'cat(R.version.string)')"
  echo "BLAS: $("$RSCRIPT" -e 'cat(extSoftVersion()[["BLAS"]])')"
  echo "VECLIB_MAXIMUM_THREADS seen by R: $("$RSCRIPT" -e 'cat(Sys.getenv("VECLIB_MAXIMUM_THREADS"))')"
  echo "lowpowermode: $(pmset -g | awk '/lowpowermode/ {print $2}')"
  echo "power: $(pmset -g batt | head -1)"
  echo "settings: replicates $REPS of $ARMS, nburn = $NB, niter = $NI, nchain = 2, cores = 5, threads = 1"
} > "$STEP-provenance.txt"
echo $$ > "$STEP-launcher.pid"
"$RSCRIPT" "$REFIT" "$WT" "$OUT" 5 "$ARMS" "$REPS" "$NB" "$NI" > "$STEP.log" 2>&1 &
RPID=$!
echo $RPID > "$STEP-rscript.pid"
caffeinate -i -w $RPID &
wait $RPID
status=$?
echo "exit status: $status at $(date '+%F %T')" >> "$STEP-provenance.txt"
echo "ALL DONE $(date '+%F %T') status $status" >> "$STEP.log"
